package Basics;

public class Variables {
    public static void main(String[] args) {
        int x = 5;
        System.out.println(x+5);
        int y; //declaration
        y = 20; //initialization
        System.out.println(y);
        System.out.println(x*y);
        System.out.println("******************************");
        int z = 7;
        System.out.println(z);
        z = z-2;
        System.out.println(z);
        z = z+20;
        System.out.println(z);
        z = z-30;
        System.out.println(z);
        z = z*10;
        System.out.println(z);
        z = z/25;
        System.out.println(z);
    }
}
