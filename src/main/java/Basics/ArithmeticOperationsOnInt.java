package Basics;

public class ArithmeticOperationsOnInt {
    public static void main(String[] args) {
        int x = 5, y = 2;
        System.out.println(x+y);
        System.out.println(x-y);
        System.out.println(x*y);
        System.out.println(x/y);

        System.out.println("************************");

        double a = 5, b = 2;
        System.out.println(a+b);
        System.out.println(a-b);
        System.out.println(a*b);
        System.out.println(a/b);
    }
}
